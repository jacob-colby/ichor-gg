"""Which gods can trigger an ally-dependent item, read off the kit (2026-11-04).

WHY. `Lotus Sickle` grants its Lotus stack only when YOUR ability "Buffed,
Healed, or Shielded another Allied God". Nothing in the pipeline asked whether
the god holding it can do that, so on `origin/main` the item reached 25 gods
through the scoring path - 23 of whom have no such ability, `Agni` among them.
It was kept out of `core` for all but `Ra` by score alone, which is luck and
not a gate: it sat in the shipped `cooldown` and `mana-stack` archetypes, which
the viewer displays. Jacob's 2026-11-03 holding measure was to strip the item's
tags (`_tags.yaml`), which lowers its score everywhere without excluding it
anywhere, and the note there asks for this gate by name.

TWO HALVES, both derived from live text so a refresh cannot leave them stale.

ITEM SIDE - `requires_allied_god`. The TRIGGER clause, not the recipient.
`_passive_classes.yaml` already has a class for the recipient question (`D1
ally-directed`, 21 items) and it is the WRONG predicate here: Triton's Conch,
Chandra's Grace and Amanita Charm all land their value on allies while
requiring nothing of your kit - the ITEM does the buffing. What this gate needs
is the passive whose CONDITION is your own ability buffing, healing or
shielding an allied god. That is a narrow, literal phrase in the wiki text, and
matching it finds exactly four buildable items:

    Lotus Sickle      "Ability Buffed, Healed, or Shielded another Allied God"
    Soul Locket       "Ability Buffed, Healed, or Shielded another Allied God"
    Eros' Bow         "Ability Buffed, Healed, or Shielded your Beloved"
    Rod of Asclepius  "Ability Healed an Ally"

Eros' Bow's `Beloved` is an ally by its own text ("Mark an ally god as your
Beloved"), so the Devotion payout - the whole point of the item - is
unreachable on a god who cannot buff them.

Deriving this from the TEXT rather than from the sidecar is deliberate: an item
the daily refresh discovers with the same trigger is gated the moment it
arrives, with no hand edit. The sidecar stays the home for the VALUE question.

GOD SIDE - `buffs_allied_god`. A god qualifies when some ability applies a
buff, heal or shield to an allied god. Three things make this harder than a
text match for "allied god", and all three were measured on the 2026-11-04
roster (94 gods):

  1. A TEXT MATCH ALONE IS FAR TOO NARROW. Searching the god files for
     "allied god" / "and allied" - the crude probe that found this defect -
     returns TWO qualifying gods of the 25 Lotus Sickle reached (Ra, Hecate).
     The real number is 31 of 94 on the base kit, 36 counting aspects. The
     corpus says "allies", "Allies hit", "your ally", "nearby allies" far more
     often than it says "allied god".

  2. `detail_kinds` ALONE IS TOO NARROW TOO. The wiki parser already tags each
     detail line `buff` / `heal` / `shield`, and requiring an ally word on a
     line so tagged finds 24 gods. It misses EIGHT who state the ally effect
     only in the ability's `description`, which carries no kinds: Ares ("You
     and nearby allied gods gain Protections and Attack Damage"), Charon,
     Ganesha, Horus, Ix Chel, Hachiman, Apollo and Artio. So both the tagged
     lines and the description are read.

  3. AN ALLY WORD NEAR A BENEFIT WORD IS TOO WIDE. The corpus is full of
     allies who are not being buffed: Hades summons "allies from the
     underworld" (minions), Charon's boat ferries them and makes them "take
     50% of the damage you take", Mercury's coins "can be picked up by
     yourself or allied gods to provide YOU 10 gold", Cu Chulainn gains Rage
     "when you or a nearby ally takes damage", and one god passes through
     "ally walls". Requiring only an ally word plus any benefit-ish verb
     admits all five.

So a clause qualifies on a GRANT RELATION plus a BENEFICIAL PAYLOAD: the ally
is the recipient of a named buff/heal/shield/protection/stat/mitigation term,
in either word order (`allies gain Protections`, `Heal the target ally`), with
no clause break between the verb and the ally. The break rule is what rejects
Cu Chulainn ("Gain Rage by hitting Abilities, per Attack, and when you or a
nearby ally takes damage" - three breaks between the verb and the ally), and
the payload list is what rejects the gold, ferry, wall and minion cases.

WHAT THE RESULT IS: the per-god verdicts and their evidence lines are
regenerated by `python -m smite.ally_kit`, and `test_ally_kit.py` pins the
roster count plus the rejection cases above, so a wiki rewording that silently
drops a god out of the set turns a test red instead of changing a build.

ASPECTS ARE A DIFFERENT KIT, and five gods turn on it - see
`buffs_allied_god`, which defaults to the BASE kit and is asked the aspect
question only for an aspect build. Getting this wrong in either direction is a
defect of the same kind as the one this module fixes.
"""
import re

#: Any reference to an allied player god. "Allied minion" / "ally wall" are
#: rejected by the payload rule below, not here.
_ALLY = re.compile(r"\ball(?:y|ies|ied)\b", re.I)

#: Verbs that put a benefit ON someone.
_GRANT = (r"heal(?:s|ed|ing)?|shield(?:s|ed|ing)?|buff(?:s|ed|ing)?|grant(?:s|ed|ing)?"
          r"|gain(?:s|ed|ing)?|receive(?:s|d)?|empower(?:s|ed|ing)?|appl(?:y|ies|ied)"
          r"|provide(?:s|d)?|bolster(?:s|ed|ing)?|increas(?:e|es|ed|ing)"
          r"|restor(?:e|es|ed|ing)|cleans(?:e|es|ed|ing)|blessed|give(?:s|n)?")

#: The thing granted has to be a buff, a heal, a shield or a stat. This is the
#: rule that rejects gold, teleports, ferrying, walls and summoned minions.
_PAYLOAD = (r"health shield|shield|heal|protections?|strength|intelligence|attack speed"
            r"|attack damage|movement speed|speed buff|damage mitigation|mitigat\w*"
            r"|reduced damage|less damage|cc immun\w*|crowd control immun\w*|immunity"
            r"|health regen|mana regen|lifesteal|penetration|cooldown|buff|beneficial"
            r"|guardian spirit\w*|omi healing|bonus(?:es)?|tenacity|max health"
            r"|damage reduction")

#: A clause break between the grant verb and the ally means the ally is not the
#: one being granted to - "Gain Rage ... and when you or a nearby ally takes
#: damage".
_BREAK = r"(?:[,;.]|\b(?:when|if|by|while|after|before|unless|until|per)\b)"
_NOBREAK = r"(?:(?!" + _BREAK + r").)"

#: Word order 1 - the ally is named, then granted something.
_ALLY_FIRST = re.compile(
    r"\ball(?:y|ies|ied)\b" + _NOBREAK + r"{0,60}?\b(?:" + _GRANT +
    r")\b.{0,40}?\b(?:" + _PAYLOAD + r")\b", re.I | re.S)
#: Word order 2 - something is granted, to the ally.
_GRANT_FIRST = re.compile(
    r"\b(?:" + _GRANT + r")\b" + _NOBREAK + r"{0,50}?\ball(?:y|ies|ied)\b",
    re.I | re.S)
#: A structured detail line, "Ally Movement Speed: 25 | 27.5".
_ALLY_STAT_LINE = re.compile(
    r"^\s*(?:ally|allied|allies)\b.{0,40}?\b(?:" + _PAYLOAD + r")\b\s*:", re.I)


def _clauses(text):
    """Sentence-ish units. The grant relation has to hold inside one."""
    return [c for c in re.split(r"(?<=[.;])\s+|\n", str(text or "")) if c.strip()]


def _ally_benefit(clause):
    """Does this clause apply a buff, heal or shield to an allied god?"""
    if not _ALLY.search(clause):
        return False
    if _ALLY_STAT_LINE.match(clause):
        return True
    if _GRANT_FIRST.search(clause) and re.search(_PAYLOAD, clause, re.I):
        return True
    return bool(_ALLY_FIRST.search(clause))


def ally_evidence(god, include_aspects=True):
    """`[(ability, where, clause)]` - every place this god's kit buffs, heals
    or shields an allied god. Empty means the god cannot trigger an
    ally-dependent item. `where` is `description`, a `detail_kinds` tag, or
    `aspect`.

    `include_aspects=False` asks the BASE-kit question, which is the one the
    non-aspect builds need - see `buffs_allied_god`."""
    out = []
    for ab in (god.get("abilities") or []):
        name = ab.get("name") or ab.get("slot") or "?"
        details = [str(d) for d in (ab.get("details") or [])]
        kinds = list(ab.get("detail_kinds") or [])
        kinds += [None] * (len(details) - len(kinds))
        parts = [(str(ab.get("description") or ""), "description")]
        parts += [(d, str(k)) for d, k in zip(details, kinds)]
        for text, where in parts:
            for clause in _clauses(text):
                if _ally_benefit(clause):
                    out.append((name, where, clause.strip()))
    if include_aspects:
        for asp in (god.get("aspects") or []):
            for clause in _clauses(str(asp.get("kit_changes") or "")):
                if _ally_benefit(clause):
                    out.append((asp.get("name") or "aspect", "aspect", clause.strip()))
    return out


#: `score_god_items` asks these questions once per (god, aspect) and once per
#: item on every archetype of every mode — thousands of calls on a
#: `calibrate` run — and both answers are fixed for the life of the process.
_GOD_CACHE = {}
_ITEM_CACHE = {}


def buffs_allied_god(god, include_aspects=False):
    """Can this god's kit buff, heal or shield an ALLIED GOD?

    THE DEFAULT IS THE BASE KIT, and that asymmetry is the point. An aspect is
    chosen at the loading screen and rewrites the kit, so the two builds are
    two different gods as far as this gate is concerned, and the roster splits
    31 base-kit qualifiers / 5 who qualify ONLY with an aspect selected
    (Bastet, Fenrir, Hercules, Jormungandr, Nut; 36 in all). Asking the
    base-kit question for an aspect build would withhold an item the player
    can use; asking the aspect question for a base build ships one they
    cannot. `score_god_items` passes `include_aspects=True` exactly when the
    profile it was given carries an aspect overlay, so each variant is asked
    about the kit it actually has.

    Two of the seven gods who ship an aspect variant turn on this distinction:
    Hercules' Aspect of Preservation ("stacks are expended to Heal nearby
    allied gods" - `_weights.yaml` already calls it the ally-heal aspect) and
    Chronos' Aspect of Relativity ("Allies in your Time Field gain bonuses"),
    neither of whom buffs an ally on the base kit."""
    key = (god.get("name"), bool(include_aspects))
    if key[0] is None:
        return bool(ally_evidence(god, include_aspects=include_aspects))
    if key not in _GOD_CACHE:
        _GOD_CACHE[key] = bool(ally_evidence(god, include_aspects=include_aspects))
    return _GOD_CACHE[key]


#: The passive's TRIGGER is your own ability buffing/healing/shielding an ally.
#: Not the same question as "the value lands on an ally" - see the module note.
_REQUIRES_ALLY = re.compile(
    r"abilit(?:y|ies)\s+(?:buffed|healed|shielded)[^.]{0,80}?"
    r"\b(?:allied god|ally|allies|beloved)\b", re.I)


def _item_text(item):
    return " ".join(str(item.get(k) or "")
                    for k in ("passive", "aura", "description", "effect"))


def requires_allied_god(item):
    """Does this item's passive need an ALLIED GOD your ability buffed?"""
    name = item.get("name")
    if name is None:
        return bool(_REQUIRES_ALLY.search(_item_text(item)))
    if name not in _ITEM_CACHE:
        _ITEM_CACHE[name] = bool(_REQUIRES_ALLY.search(_item_text(item)))
    return _ITEM_CACHE[name]


def ally_dependent_items(items):
    """Names of the items this gate can withhold."""
    return frozenset(i["name"] for i in items if requires_allied_god(i))


def excluded_for(god, items, include_aspects=False):
    """Items `god` must never be offered, because the kit cannot trigger them.
    Empty for a god who qualifies, so a qualifying god keeps full access."""
    if buffs_allied_god(god, include_aspects=include_aspects):
        return frozenset()
    return ally_dependent_items(items)


def main(argv=None):
    """Print the roster verdict and the evidence behind it."""
    from smite import recommend
    gods, items = recommend.load_gods(), recommend.load_items()
    gated = sorted(ally_dependent_items(items))
    print("ally-dependent items (%d): %s\n" % (len(gated), ", ".join(gated)))
    base = [g for g in gods if buffs_allied_god(g)]
    withasp = [g for g in gods if buffs_allied_god(g, include_aspects=True)]
    print("gods that can trigger them: %d on the base kit, %d counting aspects, of %d\n"
          % (len(base), len(withasp), len(gods)))
    for g in withasp:
        ev = ally_evidence(g, include_aspects=True)
        ab, where, clause = ev[0]
        mark = " " if buffs_allied_god(g) else "*"
        print(" %s%-16s [%s] %s: %s" % (mark, g["name"], where, ab, clause[:66]))
    print("\n* qualifies only with its aspect selected.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
